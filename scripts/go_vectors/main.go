// Emit a MoonBit test file whose expected strings come from Go's own time.Format,
// the reference for the Go reference-time layout language. Run it, then commit the
// generated src/layout_vectors_test.mbt; CI replays the tests without re-running
// Go.

package main

import (
	"fmt"
	"strings"
	"time"
)

type Case struct {
	y, m, d, h, mi, s, ns, off int
}

func loc(off int) *time.Location {
	if off == 0 {
		return time.UTC
	}
	abs := off
	sign := "+"
	if off < 0 {
		sign = "-"
		abs = -off
	}
	name := fmt.Sprintf("%s%02d:%02d", sign, abs/60, abs%60)
	// FixedZone takes seconds east of UTC, so keep the original sign.
	return time.FixedZone(name, off*60)
}

func ctor(c Case) string {
	return fmt.Sprintf("g_zoned(%d, %d, %d, %d, %d, %d, %d, %d)", c.y, c.m, c.d, c.h, c.mi, c.s, c.ns, c.off)
}

func main() {
	cases := []Case{
		{y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, ns: 123456789, off: 480},
		{y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, ns: 123456789, off: 0},
		{y: 1999, m: 1, d: 5, h: 3, mi: 4, s: 7, ns: 0, off: 0},
		{y: 2000, m: 2, d: 29, h: 23, mi: 59, s: 59, ns: 0, off: -330},
		{y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, ns: 123456789, off: 0},
	}

	layouts := []string{
		"2006-01-02T15:04:05Z07:00",
		"2006-01-02T15:04:05.999999999Z07:00",
		"Mon Jan _2 15:04:05 2006",
		"Mon Jan _2 15:04:05 MST 2006",
		"Mon Jan 02 15:04:05 -0700 2006",
		"02 Jan 06 15:04 MST",
		"02 Jan 06 15:04 -0700",
		"Monday, 02-Jan-06 15:04:05 MST",
		"Mon, 02 Jan 2006 15:04:05 MST",
		"Mon, 02 Jan 2006 15:04:05 -0700",
		"3:04PM",
		"Jan _2 15:04:05",
		"Jan _2 15:04:05.000",
		"Jan _2 15:04:05.000000",
		"Jan _2 15:04:05.000000000",
		"2006-01-02 15:04:05",
		"2006-01-02",
		"15:04:05",
		"2006/01/02 15:04:05.000 -07:00",
		"02/01/2006 03:04:05 PM",
		"Mon, 02 Jan 2006 15:04:05 -07:00",
		"2006-01-02 15:04:05.999 -0700",
		"Monday, 02-Jan-06 15:04:05 -0700",
	}

	fmt.Println("// Generated by scripts/go_vectors from Go's time.Format.")
	fmt.Println("// The expected strings are Go's own output; do not edit by hand.")
	fmt.Println()
	fmt.Println("fn g_zoned(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, sec : Int32, u : Int32, off : Int32) -> @moondate.Moment raise @moondate.Refused {")
	fmt.Println("  @moondate.Moment::Zoned(date=@moondate.Date::new(y, m, d), time=@moondate.Time::new(hh, mi, second=sec, nano=u), zone=@moondate.Offset(off))")
	fmt.Println("}")
	fmt.Println()

	idx := 0
	for _, ly := range layouts {
		for _, c := range cases {
			t := time.Date(c.y, time.Month(c.m), c.d, c.h, c.mi, c.s, c.ns, loc(c.off))
			got := t.Format(ly)
			shown := strings.ReplaceAll(got, `\`, `\\`)
			shown = strings.ReplaceAll(shown, `"`, `\"`)
			fmt.Printf("test \"go layout %d\" {\n", idx)
			fmt.Printf("  assert_eq(%s.layout(%q), %q)\n", ctor(c), ly, shown)
			fmt.Println("}")
			fmt.Println()
			idx++
		}
	}
}
