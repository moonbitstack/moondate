// Emit a MoonBit test file whose expected strings come from Rust chrono's
// strftime, the reference for the directives chrono adds (the colon offset
// forms, space-padded hours, the fractional-second widths, %+).

use chrono::{DateTime, FixedOffset, TimeZone, Timelike};

struct Case {
    y: i32, m: u32, d: u32, h: u32, mi: u32, s: u32, nanos: u32, off_min: i32,
}

fn dt(c: &Case) -> DateTime<FixedOffset> {
    let off = FixedOffset::east_opt(c.off_min * 60).unwrap();
    off.with_ymd_and_hms(c.y, c.m, c.d, c.h, c.mi, c.s)
        .unwrap()
        .with_nanosecond(c.nanos)
        .unwrap()
}

fn moonbit_ctor(c: &Case) -> String {
    format!(
        "vc_zoned({}, {}, {}, {}, {}, {}, {}, {})",
        c.y, c.m, c.d, c.h, c.mi, c.s, c.nanos, c.off_min
    )
}

fn main() {
    let cases = vec![
        Case { y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, nanos: 123456789, off_min: 480 },
        Case { y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, nanos: 123456789, off_min: 0 },
        Case { y: 1999, m: 1, d: 5, h: 3, mi: 4, s: 7, nanos: 0, off_min: 0 },
        Case { y: 2000, m: 2, d: 29, h: 23, mi: 59, s: 59, nanos: 0, off_min: -330 },
        Case { y: 2026, m: 9, d: 22, h: 14, mi: 30, s: 5, nanos: 123456789, off_min: 0 },
    ];

    // NOTE: `%:::z` drops the minutes of a half-hour offset in chrono (`-05` for
    // `-05:30`), while glibc's rule is the offset at the precision it needs
    // (`-05:30`). The library follows glibc, so that one case is left out here and
    // checked in src/strftime_offset_test.mbt instead.
    //
    // NOTE: `%f` is intentionally omitted here. This project's `%f` follows
    // Python (six microsecond digits) per the task spec, which differs from
    // chrono's nine-digit `%f`. The six-digit form is covered by the CPython
    // oracle (scripts/gen_strftime_vectors.py) instead.
    let formats = [
        "%k", "%l", "%3f", "%9f", "%.6f", "%:z", "%::z", "%:::z", "%+",
    ];

    println!("// Generated by scripts/chrono_vectors from Rust chrono's strftime.");
    println!("// The expected strings are chrono's own output; do not edit by hand.");
    println!();
    println!("fn vc_zoned(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, sec : Int32, u : Int32, off : Int32) -> @moondate.Moment raise @moondate.Refused {{");
    println!("  @moondate.Moment::Zoned(date=@moondate.Date::new(y, m, d), time=@moondate.Time::new(hh, mi, second=sec, nano=u), zone=@moondate.Offset(off))");
    println!("}}");
    println!();

    for (i, c) in cases.iter().enumerate() {
        println!("test \"chrono vectors #{}\" {{", i);
        for fmt in &formats {
            if *fmt == "%:::z" && c.off_min % 60 != 0 {
                continue;
            }
            let expected = match dt(c).format(fmt).to_string() {
                v if v.contains('\n') => v.replace('\n', "\\n"),
                v => v,
            };
            let shown = expected.replace('\\', "\\\\").replace('"', "\\\"");
            // %N is GNU date's nine-digit nanoseconds; chrono's %9f writes the same.
            let mb_fmt = if *fmt == "%9f" { "%N" } else { fmt };
            println!(
                "  assert_eq({}.strftime(\"{}\"), \"{}\")",
                moonbit_ctor(c),
                mb_fmt,
                shown
            );
        }
        println!("}}");
        println!();
    }

    // A round-trip check that chrono's %+ reads back through parse what it wrote.
    println!("// chrono's %+ round-trips to the same instant.");
}
