#!/usr/bin/env python3
"""The same TZif files read two ways, compared against the release.

The tree is the one the machine installs — the IANA release, so the bytes are the
same ones a `zic` build would give — and Python's `zoneinfo` reads them to say
what the offset is at each instant, so what the two MoonBit readers are compared
on is the lookup rather than either of them.

    scripts/tzif_diff/build.py                      # write the package
    scripts/tzif_diff/build.py --check              # fail if it is stale

Two readers are asked for each instant: this library's TZif reader and
`moonbitlang/x`'s `Zone::from_tzif`. The checker, in `lib.mbt`, walks the
instants and returns the disagreements as text; the test runs it and asserts
there are none. The checker is build code, so the package it imports is used,
and the test is a thin replay of it. A file one of the readers will not read is
counted, not a failure: a reader that refuses a file is not wrong about the file
it did read.
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
PKG_DIR = os.path.join(ROOT, "integration", "tzif_diff")
LIB = os.path.join(PKG_DIR, "lib.mbt")
TEST = os.path.join(PKG_DIR, "tzif_diff_wbtest.mbt")
PKG = os.path.join(PKG_DIR, "moon.pkg")

# A fixed zone, one whose offset is not a whole hour, one with sub-hour saving,
# and zones with two changes a year on each side of the equator, so a footer rule
# is exercised in both directions.
FIXTURES = [
    "Etc/UTC",
    "Asia/Kathmandu",
    "Asia/Kolkata",
    "America/New_York",
    "Australia/Sydney",
    "Pacific/Chatham",
    "Europe/Berlin",
]

LOW = -5364662400  # 1800-01-01
HIGH = 4133980800  # 2101-01-01
# Two instants past the end of every table, read from the POSIX rule in the
# footer: one in each season, so a rule that moves the clocks twice a year is
# asked on both sides of the change.
PROBES = [4103654400, 4119292800]


def read_tzif(path: str) -> bytes:
    with open(path, "rb") as handle:
        return handle.read()


def transitions(data: bytes) -> list[int]:
    """The transition times of the block a reader actually uses, the 64-bit one
    when the file is version 2 or later and the 32-bit one otherwise."""
    if data[:4] != b"TZif":
        return []
    version = data[4:5]
    isut, isstd, leap, times, types, chars = struct.unpack(">6I", data[20:44])

    def length(width):
        return times * width + times + types * 6 + chars + leap * (width + 4) + isstd + isut

    if version in (b"2", b"3", b"4"):
        head = 44 + length(4)
        version = data[head + 4 : head + 5]
        isut, isstd, leap, times, types, chars = struct.unpack(">6I", data[head + 20 : head + 44])
        base, width = head + 44, 8
    else:
        base, width = 44, 4
    out = []
    for k in range(times):
        at = base + k * width
        out.append(struct.unpack(">q" if width == 8 else ">i", data[at : at + width])[0])
    return out


def offset_at(name: str, when: int) -> int:
    from datetime import datetime, timedelta, timezone
    from zoneinfo import ZoneInfo

    moment = (datetime(1970, 1, 1, tzinfo=timezone.utc) + timedelta(seconds=when)).astimezone(
        ZoneInfo(name)
    )
    return int(moment.utcoffset().total_seconds())


LIB_HEADER = """// Generated by scripts/tzif_diff/build.py, DON'T EDIT IT.
//
// The same TZif files read by this library's reader and by `moonbitlang/x`'s
// `Zone::from_tzif`, against the offset the release says at each instant, which
// is Python's `zoneinfo` reading the same bytes. `diff_zones` and `diff_files`
// are parallel: the `i`th file is the bytes the `i`th zone is filed under, and
// `diff_instants` is each instant asked about, with the offset the release says.
//
// The checker below walks the instants and returns the disagreements as text;
// the test in `tzif_diff_wbtest.mbt` runs it and asserts there are none. The
// checker is build code, so the package it imports is used.

///|
/// The zones, in the order their files sit beside them.
let diff_zones : Array[String] = [
"""

LIB_FOOTER = """]

///|
/// The bytes each zone is filed under, in hexadecimal.
let diff_files : Array[String] = [
"""

LIB_TAIL = """]

///|
/// Each instant asked about: the zone, the instant, the offset the release says.
let diff_instants : Array[(String, Int64, Int32)] = [
"""

CHECKERS = """
///|
/// The bytes a zone is filed under, from the hexadecimal they are written in.
fn diff_hex_bytes(text : String) -> Bytes {
  @base16.decode(text) catch {
    _ => abort("a fixture in this file is not hexadecimal")
  }
}

///|
/// The index a zone is filed under, or -1 when it is not one of the files.
pub fn diff_index_of(wanted : String) -> Int32 {
  let mut i = 0
  for zone in diff_zones {
    if zone == wanted {
      return i
    }
    i = i + 1
  }
  -1
}

///|
/// The file a zone is filed under, as the bytes it was read from.
fn diff_bytes_of(i : Int32) -> Bytes {
  diff_hex_bytes(diff_files[i])
}

///|
/// The zone a zone is filed under, read from its bytes.
pub fn diff_tz_of(i : Int32) -> @zone.Tz? {
  let zone = diff_zones[i]
  Some(@zone.Tz::parse(diff_bytes_of(i), name=zone)) catch { _ => None }
}

///|
/// The zone a zone is filed under, read by the other reader.
pub fn diff_x_of(i : Int32) -> @time.Zone? {
  let zone = diff_zones[i]
  Some(@time.Zone::from_tzif(zone, diff_bytes_of(i)[:])) catch { _ => None }
}

///|
/// The instants the library's reader does not read the way the release says, one
/// per line: `zone at epoch: read X, want Y`, or `: not read` when it refuses.
pub fn diff_against_release() -> Array[String] {
  let wrong : Array[String] = []
  for (zone, epoch, want) in diff_instants {
    let index = diff_index_of(zone)
    if index < 0 {
      continue
    }
    match diff_tz_of(index) {
      None => wrong.push(zone + " at " + epoch.to_string() + ": not read")
      Some(tz) =>
        if tz.offset(epoch) != want {
          wrong.push(
            zone + " at " +
            epoch.to_string() +
            ": read " +
            tz.offset(epoch).to_string() +
            ", want " +
            want.to_string(),
          )
        }
    }
  }
  wrong
}

///|
/// The instants the two readers do not agree on, one per line: `zone at epoch:
/// here X, x Y`. A file one reader will not read is not a disagreement, so it is
/// left out rather than counted as one.
pub fn diff_between_readers() -> Array[String] {
  let wrong : Array[String] = []
  for (zone, epoch, _) in diff_instants {
    let index = diff_index_of(zone)
    if index < 0 {
      continue
    }
    match (diff_tz_of(index), diff_x_of(index)) {
      (None, _) | (_, None) => ()
      (Some(tz), Some(zone_x)) => {
        // The other reader refuses an instant that is out of its range, which is
        // not a disagreement about an instant it answered, so it is left out.
        let zoned_x = Some(@time.unix(epoch, zone=zone_x)) catch { _ => None }
        match zoned_x {
          None => ()
          Some(zdt) => {
            let offset_x = zdt.offset().seconds()
            if tz.offset(epoch) != offset_x {
              wrong.push(
                zone + " at " +
                epoch.to_string() +
                ": here " +
                tz.offset(epoch).to_string() +
                ", x " +
                offset_x.to_string(),
              )
            }
          }
        }
      }
    }
  }
  wrong
}

///|
/// The number of instants both readers read, so a test can say the comparison was
/// not vacuous.
pub fn diff_compared() -> Int32 {
  let mut compared = 0
  for (zone, _, _) in diff_instants {
    let index = diff_index_of(zone)
    if index < 0 {
      continue
    }
    if diff_tz_of(index) is Some(_) && diff_x_of(index) is Some(_) {
      compared = compared + 1
    }
  }
  compared
}
"""

TEST_BODY = """
///|
test "the same TZif file read by the library gives the release's offset" {
  // The release is Python's `zoneinfo` reading the same bytes, so the offset each
  // instant carries is what the file says at that instant.
  assert_eq(diff_against_release(), [])
  assert_true(diff_instants.length() > 0)
}

///|
test "the two readers read the same offset at the same instants" {
  // The two readers agree on every instant they both read, and at least one file
  // is compared, so the comparison is not vacuous.
  assert_eq(diff_between_readers(), [])
  assert_true(diff_compared() > 0)
}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="write nothing; fail if stale")
    args = parser.parse_args()

    zoneinfo = os.environ.get("TZDIR", "/usr/share/zoneinfo")
    zones = []
    files = []
    instants = []  # (name, epoch, offset)
    for name in FIXTURES:
        path = os.path.join(zoneinfo, *name.split("/"))
        if not os.path.exists(path):
            sys.stderr.write("skipping {}: not there\n".format(name))
            continue
        data = read_tzif(path)
        known = [t for t in transitions(data) if LOW <= t < HIGH]
        picks = sorted(set(known) | set(PROBES))
        zones.append(name)
        files.append(data.hex())
        for t in picks:
            instants.append((name, t, offset_at(name, t)))

    lib = [LIB_HEADER]
    for z in zones:
        lib.append('  "{}",'.format(z))
    lib.append(LIB_FOOTER)
    for f in files:
        lib.append('  "{}",'.format(f))
    lib.append(LIB_TAIL)
    for name, epoch, offset in instants:
        lib.append('  ("{}", {}L, {}),'.format(name, epoch, offset))
    lib.append("]")
    lib.append("")
    lib.append(CHECKERS)
    lib_full = "\n".join(lib) + "\n"

    test_full = (
        "// Generated by scripts/tzif_diff/build.py, DON'T EDIT IT.\n"
        "//\n"
        "// The replay of the checker in `lib.mbt`: two tests, one against the\n"
        "// release and one between the two readers.\n"
        + TEST_BODY
    )
    # A run that found none of the files would write an empty bench over
    # a good one, and the test that replays it would pass on nothing.
    if not files:
        sys.stderr.write("no zone files under {}; nothing written\n".format(zoneinfo))
        raise SystemExit(1)

    pkg_text = (
        "import {\n"
        '  "moonbitstack/moondate/zone",\n'
        '  "moonbitstack/moonbase/base16",\n'
        '  "moonbitlang/x/time",\n'
        "}\n"
    )

    if args.check:
        with open(LIB, encoding="utf-8") as handle:
            if handle.read() != lib_full:
                sys.stderr.write("{} is stale\n".format(LIB))
                raise SystemExit(1)
        with open(TEST, encoding="utf-8") as handle:
            if handle.read() != test_full:
                sys.stderr.write("{} is stale\n".format(TEST))
                raise SystemExit(1)
        print("the differential is what the release gives")
        return 0
    os.makedirs(PKG_DIR, exist_ok=True)
    with open(LIB, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(lib_full)
    with open(TEST, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(test_full)
    with open(PKG, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(pkg_text)
    print(
        "wrote integration/tzif_diff ({} files, {} instants, {} bytes of TZif)".format(
            len(zones), len(instants), sum(len(f) for f in files),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
