# Emit a MoonBit test file whose expected strings come from Babel's LDML date
# patterns (`format_datetime(locale="en")`), the reference for the UTS #35 pattern
# letters. Run it, then commit the generated src/pattern_vectors_test.mbt; CI
# replays the tests without re-running Python.

import datetime
import sys

from babel.dates import format_datetime

# Each case is a wall clock plus an offset in minutes. The offsets are chosen so
# that Babel formats them correctly: its zone output is wrong for a negative offset
# whose minutes are not zero (`-5:30` comes out as `-06:30`), so the west-bound case
# is a whole hour and the sub-hour case is east-bound.
CASES = [
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, us=123456, off=480),
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, us=123456, off=0),
    dict(y=1999, m=1, d=5, H=3, M=4, S=7, us=0, off=-300),
    dict(y=2000, m=2, d=29, H=23, M=59, S=59, us=0, off=330),
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, us=123456, off=0),
]

# Field patterns that do not carry a zone, then the zone patterns.
PATTERNS = [
    "yyyy-MM-dd", "y-M-d", "yy", "y", "Y", "u", "G", "GGGG", "Q", "QQ",
    "QQQ", "QQQQ", "M", "MM", "MMM", "MMMM", "MMMMM", "L", "LLL", "LLLL",
    "w", "ww", "W", "d", "dd", "D", "DDD", "F", "E", "EEE", "EEEE",
    "EEEEE", "EEEEEE", "e", "ee", "eee", "eeee", "a", "h", "hh", "H",
    "HH", "K", "KK", "k", "kk", "m", "mm", "s", "ss", "S", "SSS",
    "SSSSSSSSS", "A", "h:mm a", "HH:mm:ss", "'at' HH:mm",
    "yyyy-MM-dd'T'HH:mm:ss",
    "z", "Z", "ZZZZ", "ZZZZZ", "OOOO", "X", "XX", "XXX", "XXXX", "XXXXX",
    "x", "xxx", "yyyy-MM-dd'T'HH:mm:ssXXX",
]


def dt_of(c):
    base = datetime.datetime(c["y"], c["m"], c["d"], c["H"], c["M"], c["S"], c["us"])
    tz = datetime.timezone(datetime.timedelta(minutes=c["off"]))
    return base.replace(tzinfo=tz)


def ctor(c):
    return "p_zoned(%d, %d, %d, %d, %d, %d, %d, %d)" % (
        c["y"], c["m"], c["d"], c["H"], c["M"], c["S"], c["us"] * 1000, c["off"],
    )


def escape(s):
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )


def main():
    out = []
    out.append("// Generated by scripts/gen_pattern_vectors.py from Babel's LDML patterns.")
    out.append("// The expected strings are Babel's own output; do not edit by hand.")
    out.append("")
    out.append(
        "fn p_zoned(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, "
        "sec : Int32, u : Int32, off : Int32) -> @moondate.Moment raise @moondate.Refused {"
    )
    out.append(
        "  @moondate.Moment::Zoned(date=@moondate.Date::new(y, m, d), "
        "time=@moondate.Time::new(hh, mi, second=sec, nano=u), "
        "zone=@moondate.Offset(off))"
    )
    out.append("}")
    out.append("")

    idx = 0
    for pat in PATTERNS:
        for c in CASES:
            expected = format_datetime(dt_of(c), format=pat, locale="en")
            out.append('test "pattern %d" {' % idx)
            out.append(
                '  assert_eq(%s.pattern("%s"), "%s")'
                % (ctor(c), escape(pat), escape(expected))
            )
            out.append("}")
            out.append("")
            idx += 1
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
