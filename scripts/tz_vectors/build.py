#!/usr/bin/env python3
"""Turn a TZif tree into the vectors the tests replay.

The tree comes from the release's own `zic`, run over the compendium this package
carries, so the two reference implementations and this library are all reading the
same bytes:

    scripts/gen_tzdata.py --from-dir $TZDATA      # data.mbt
    zic -b fat -d /tmp/tzif tzdata.zi             # TZif tree
    scripts/tz_vectors/build.py --tzif /tmp/tzif  # the tests

Python's zoneinfo and Go's time are both asked, and their answers are compared
before either is written down: a vector nobody else agrees with is not a vector.

Two files come out: the transitions of every zone between 1800 and 2100 for the
tzdata tests, and three real TZif files with the readings they must give for the
zone tests.
"""

from __future__ import annotations

import argparse
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TZDATA_OUT = os.path.join(ROOT, "src", "tzdata", "transition_vectors_wbtest.mbt")
ZONE_OUT = os.path.join(ROOT, "src", "zone", "tzif_files_wbtest.mbt")

# A zone with no transitions, one whose offset is not a whole hour, and one with
# two changes a year and a footer that carries them past the end of the table.
FIXTURES = ["Etc/UTC", "Asia/Kathmandu", "America/New_York"]

# 1900-01-01, 1938-04-24, 1970-01-01, 2001-09-09, 2026-11-01, 2100-01-01.
SAMPLES = [-2208988800, -1000000000, 0, 1000000000, 1793511000, 4102444800]

LINES_PER_CHUNK = 40


def run(program: list[str], env: dict[str, str] | None = None) -> str:
    done = subprocess.run(program, capture_output=True, text=True, env=env)
    if done.returncode != 0:
        sys.stderr.write(done.stderr)
        raise SystemExit("{} failed".format(program[0]))
    if done.stderr.strip():
        sys.stderr.write(done.stderr)
    return done.stdout


def records(text: str):
    out = []
    for line in text.splitlines():
        if not line.strip():
            continue
        name, epoch, offset, abbrev, daylight = line.split()
        out.append((name, int(epoch), int(offset), abbrev, int(daylight)))
    return out


def compare(from_python, from_go) -> None:
    """Every instant both were asked about, answered the same way.

    Go reports no daylight flag, so the two are compared on the offset and the
    name, which is all the format lets Go say.
    """
    go = {(name, epoch): (offset, abbrev) for name, epoch, offset, abbrev, _ in from_go}
    if len(go) != len(from_go):
        raise SystemExit("go answered the same instant twice")
    trouble = 0
    for name, epoch, offset, abbrev, _ in from_python:
        there = go.get((name, epoch))
        if there is None:
            raise SystemExit("go did not answer {} at {}".format(name, epoch))
        if there != (offset, abbrev):
            print(
                "disagree: {} at {} python {}/{} go {}/{}".format(
                    name, epoch, offset, abbrev, there[0], there[1]
                ),
                file=sys.stderr,
            )
            trouble += 1
    if trouble:
        raise SystemExit("the two references disagree in {} places".format(trouble))
    print("instants both references agree on: {}".format(len(from_python)))


def settle(vectors):
    """Keep the points where the zone actually changed its mind.

    The instants handed in are candidates: a TZif file may list a transition that
    changes nothing, and the scan past the end of a table only narrows the second,
    so what is worth replaying is where the answer differs from the one before.
    """
    out = []
    last = {}
    for name, epoch, offset, abbrev, daylight in vectors:
        was = last.get(name)
        if was == (offset, abbrev, daylight):
            continue
        last[name] = (offset, abbrev, daylight)
        out.append((name, epoch, offset, abbrev, daylight))
    return out


def escape(line: str) -> str:
    return (
        line.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\t", "\\t")
        .replace("\n", "\\n")
    )


def render_transitions(vectors) -> str:
    lines = []
    name = None
    for zone, epoch, offset, abbrev, daylight in vectors:
        if zone != name:
            lines.append("Z " + zone)
            name = zone
        lines.append("{} {} {} {}".format(epoch, offset, abbrev, daylight))
    out = [
        "// Generated by scripts/tz_vectors/build.py, DON'T EDIT IT.",
        "//",
        "// Every transition of every zone between 1800 and 2100, as Python's",
        "// zoneinfo and Go's time both read them out of a tree compiled by the",
        "// release's own zic.",
        "",
        "///|",
        "/// The transitions, one zone after another.",
        "let transition_chunks : Array[String] = [",
    ]
    for start in range(0, len(lines), LINES_PER_CHUNK):
        chunk = "\n".join(lines[start : start + LINES_PER_CHUNK])
        out.append('  "{}",'.format(escape(chunk)))
    out.append("]")
    out.append("")
    return "\n".join(out)


def first_block(data: bytes) -> bytes:
    """A version 2 file with everything from its second header on cut away is
    exactly the version 1 file the format says it carries."""
    isut, isstd, leap, times, types, chars = struct.unpack(">6I", data[20:44])
    cut = bytearray(
        data[: 44 + times * 4 + times + types * 6 + chars + leap * 8 + isstd + isut]
    )
    # A version 1 file says so in its fifth byte; the block itself is the one a
    # version 2 file keeps for a reader that predates 2038.
    cut[4] = 0
    return bytes(cut)


def render_files(tzif: str, vectors) -> str:
    out = [
        "// Generated by scripts/tz_vectors/build.py, DON'T EDIT IT.",
        "//",
        "// Real TZif files, and the first block of each on its own, which is the",
        "// version 1 file the format carries for a reader written before 2038.",
        "",
        "///|",
        "/// `(name, version 2 bytes, version 1 bytes)`, in hexadecimal.",
        "let tzif_files : Array[(String, String, String)] = [",
    ]
    for name in FIXTURES:
        with open(os.path.join(tzif, *name.split("/")), "rb") as handle:
            data = handle.read()
        out.append(
            '  ("{}", "{}", "{}"),'.format(name, data.hex(), first_block(data).hex())
        )
    out.append("]")
    out.append("")
    out.append("///|")
    out.append("/// `(name, instant, offset, abbreviation, daylight)`, from the references.")
    out.append("let tzif_samples : Array[(String, Int64, Int32, String, Bool)] = [")
    for name, epoch, offset, abbrev, daylight in vectors:
        if name in FIXTURES and epoch in SAMPLES:
            out.append(
                '  ("{}", {}L, {}, "{}", {}),'.format(
                    name, epoch, offset, abbrev, "true" if daylight else "false"
                )
            )
    out.append("]")
    out.append("")
    return "\n".join(out)


def write(path: str, body: str, check: bool) -> None:
    if check:
        with open(path, encoding="utf-8") as handle:
            if handle.read() != body:
                raise SystemExit("{} is stale".format(path))
        return
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(body)
    print("wrote {} ({} kB)".format(os.path.relpath(path, ROOT), len(body) // 1024))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tzif", required=True, help="a tree built by zic")
    parser.add_argument("--python", help="reuse a vectors.py run")
    parser.add_argument("--go", help="reuse a vectors.go run")
    parser.add_argument("--instants", help="reuse an instants.py run")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail when the committed vectors are stale",
    )
    args = parser.parse_args()
    listing = args.instants
    if listing is None:
        listing = os.path.join(tempfile.mkdtemp(), "instants.txt")
        with open(listing, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(
                run([sys.executable, os.path.join(HERE, "instants.py"), args.tzif])
            )
    from_python = records(
        open(args.python, encoding="utf-8").read()
        if args.python
        else run([sys.executable, os.path.join(HERE, "vectors.py"), args.tzif, listing])
    )
    from_go = records(
        open(args.go, encoding="utf-8").read()
        if args.go
        else run(["go", "run", os.path.join(HERE, "vectors.go"), args.tzif, listing])
    )
    compare(from_python, from_go)
    settled = settle(from_python)
    write(TZDATA_OUT, render_transitions(settled), args.check)
    write(ZONE_OUT, render_files(args.tzif, settled), args.check)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
