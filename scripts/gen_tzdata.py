#!/usr/bin/env python3
"""Turn an IANA tzdata release into the MoonBit source that carries it.

The release ships its own compendium — `tzdata.zi`, made by the release's own
`ziguard.awk` and `zishrink.awk` — and that is what goes into the package: 105 kB
of `Rule`, `Zone` and `Link` lines, a tenth the size of the compiled TZif tree and
readable in a diff when a release lands.

    scripts/gen_tzdata.py                    # fetch the newest release
    scripts/gen_tzdata.py --release 2026f    # pin one
    scripts/gen_tzdata.py --from-dir DIR     # use an unpacked release
    scripts/gen_tzdata.py --check            # fail if the output is stale
"""

from __future__ import annotations

import argparse
import hashlib
import io
import os
import subprocess
import sys
import tarfile
import tempfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "tzdata", "data.mbt")

# The files zishrink reads, in the order the release's Makefile lists them.
SOURCES = [
    "africa",
    "antarctica",
    "asia",
    "australasia",
    "europe",
    "northamerica",
    "southamerica",
    "etcetera",
    "backward",
    "factory",
]

CHUNK = 1400


def fetch(release: str | None) -> dict[str, bytes]:
    url = (
        "https://data.iana.org/time-zones/releases/tzdata{}.tar.gz".format(release)
        if release
        else "https://data.iana.org/time-zones/tzdata-latest.tar.gz"
    )
    with urllib.request.urlopen(url) as response:
        blob = response.read()
    files: dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(blob)) as tar:
        for member in tar.getmembers():
            if member.isfile():
                files[member.name] = tar.extractfile(member).read()
    return files


def read_dir(path: str) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for name in os.listdir(path):
        full = os.path.join(path, name)
        if os.path.isfile(full):
            with open(full, "rb") as handle:
                files[name] = handle.read()
    return files


def compendium(files: dict[str, bytes]) -> tuple[str, str]:
    """The release's `ziguard.awk` then `zishrink.awk`, exactly as its Makefile
    runs them, so the text in the package is the text IANA publishes."""
    if "tzdata.zi" in files:
        text = files["tzdata.zi"].decode()
        version = files["version"].decode().strip()
        return text, version
    with tempfile.TemporaryDirectory() as work:
        for name, body in files.items():
            with open(os.path.join(work, name), "wb") as handle:
                handle.write(body)
        version = files["version"].decode().strip()
        guarded = subprocess.run(
            ["awk", "-v", "DATAFORM=main", "-f", "ziguard.awk", *SOURCES],
            cwd=work,
            check=True,
            capture_output=True,
        ).stdout
        shrunk = subprocess.run(
            [
                "awk",
                "-v",
                "dataform=main",
                "-v",
                "deps=main.zi zishrink.awk",
                "-v",
                "redo=",
                "-v",
                f"version={version}",
                "-f",
                "zishrink.awk",
                "-",
            ],
            cwd=work,
            check=True,
            input=guarded,
            capture_output=True,
        ).stdout
        return shrunk.decode(), version


def escape(line: str) -> str:
    out = line.replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\t", "\\t").replace("\n", "\\n")


def render(text: str, version: str) -> str:
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    chunks: list[str] = []
    current: list[str] = []
    size = 0
    for line in lines:
        current.append(line)
        size += len(line) + 1
        if size >= CHUNK:
            chunks.append("\n".join(current))
            current = []
            size = 0
    if current:
        chunks.append("\n".join(current))
    digest = hashlib.sha256(text.encode()).hexdigest()
    out = [
        "// Generated by scripts/gen_tzdata.py from the IANA release named below,",
        "// DON'T EDIT IT. Run the script again to move to a new release.",
        "",
        "///|",
        "/// The IANA release this package carries.",
        "pub let release : String = \"{}\"".format(version),
        "",
        "///|",
        "/// The SHA-256 of the source text below, so a release can be recognised",
        "/// without reading the whole of it.",
        "pub let source_digest : String = \"{}\"".format(digest),
        "",
        "///|",
        "/// The release's own compendium, in the chunks the source is written in.",
        "let chunks : Array[String] = [",
    ]
    for chunk in chunks:
        out.append('  "{}",'.format(escape(chunk)))
    out.append("]")
    out.append("")
    out.append("///|")
    out.append("/// The compendium as one string.")
    out.append("fn source_text() -> String {")
    out.append("  let out = StringBuilder()")
    out.append("  for chunk in chunks {")
    out.append("    out.write_string(chunk)")
    out.append('    out.write_string("\\n")')
    out.append("  }")
    out.append("  out.to_string()")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--release", help="the release to pin, e.g. 2026f")
    parser.add_argument("--from-dir", help="an unpacked release directory")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail when data.mbt is not what the release gives",
    )
    parser.add_argument(
        "--keep",
        help="also write the compendium to this directory, for zic to compile",
    )
    args = parser.parse_args()
    files = read_dir(args.from_dir) if args.from_dir else fetch(args.release)
    text, version = compendium(files)
    body = render(text, version)
    if args.check:
        with open(OUT, encoding="utf-8") as handle:
            have = handle.read()
        if have != body:
            print("src/tzdata/data.mbt is not what the release gives", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(body)
    if args.keep:
        os.makedirs(args.keep, exist_ok=True)
        with open(
            os.path.join(args.keep, "tzdata.zi"), "w", encoding="utf-8", newline="\n"
        ) as handle:
            handle.write(text if text.endswith("\n") else text + "\n")
    zones = sum(1 for line in text.split("\n") if line.startswith("Z "))
    links = sum(1 for line in text.split("\n") if line.startswith("L "))
    rules = sum(1 for line in text.split("\n") if line.startswith("R "))
    print(
        "{}: {} zones, {} links, {} rules, {} bytes".format(
            version, zones, links, rules, len(text.encode())
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
