// Emit a MoonBit test file whose expected strings come from Node's Date, the
// reference for ECMA-262's Date Time String Format: `toISOString` and
// `toUTCString`. The `isoformat` fraction and offset variants are derived from the
// same `toISOString` string (Node's Date only carries milliseconds, so the
// nanosecond-only cases are checked separately in src/ecma_test.mbt).
//
// Run with: node scripts/gen_ecma_vectors.js > src/ecma_vectors_test.mbt

function pad(n, w) {
  let s = String(n);
  while (s.length < w) s = "0" + s;
  return s;
}

const cases = [
  { y: 2026, mo: 9, d: 22, h: 14, mi: 30, s: 5, ms: 0 },
  { y: 2026, mo: 9, d: 22, h: 14, mi: 30, s: 5, ms: 123 },
  { y: 1999, mo: 1, d: 5, h: 3, mi: 4, s: 7, ms: 0 },
  { y: 2000, mo: 2, d: 29, h: 23, mi: 59, s: 59, ms: 0 },
  { y: 2026, mo: 9, d: 22, h: 14, mi: 30, s: 5, ms: 500 },
  { y: 2026, mo: 9, d: 22, h: 14, mi: 30, s: 5, ms: 999 },
];

function dateOf(c) {
  return new Date(Date.UTC(c.y, c.mo - 1, c.d, c.h, c.mi, c.s, c.ms));
}

function ctor(c) {
  return `e_utc(${c.y}, ${c.mo}, ${c.d}, ${c.h}, ${c.mi}, ${c.s}, ${c.ms})`;
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

// The fractional digits the moment carries, as `count` digits (millis + zeros).
function fracDigits(millis3, count) {
  let base = millis3 + "000000"; // 9 digits worth
  return base.slice(0, count);
}

// Temporal "auto": trim trailing zeros and drop the dot when nothing is left.
function auto(isoStr) {
  const dot = isoStr.indexOf(".");
  if (dot < 0) return isoStr;
  const head = isoStr.slice(0, dot);
  let digits = isoStr.slice(dot + 1).replace(/Z$/, "").replace(/0+$/, "");
  return digits.length ? head + "." + digits + "Z" : head + "Z";
}

const out = [];
out.push("// Generated by scripts/gen_ecma_vectors.js from Node's Date.");
out.push("// The expected strings are Node's own output; do not edit by hand.");
out.push("");
out.push(
  "fn e_utc(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, sec : Int32, u : Int32) -> @moondate.Moment raise @moondate.Refused {",
);
out.push(
  "  @moondate.Moment::Zoned(date=@moondate.Date::new(y, m, d), time=@moondate.Time::new(hh, mi, second=sec, nano=u * 1_000_000), zone=@moondate.Utc)",
);
out.push("}");
out.push("");

let idx = 0;
for (const c of cases) {
  const d = dateOf(c);
  const iso = d.toISOString();
  const utc = d.toUTCString();
  const secs = iso.slice(0, 19) + "Z";
  const millis3 = pad(c.ms, 3);

  const checks = [];
  checks.push(["to_iso_string()", esc(iso)]);
  checks.push(["to_utc_string()", esc(utc)]);
  checks.push(["isoformat(fraction=3)", esc(iso)]);
  checks.push(["isoformat(fraction=0)", esc(secs)]);
  checks.push(["isoformat(fraction=-1)", esc(auto(iso))]);
  checks.push(["isoformat(fraction=3, offset=false)", esc(iso.slice(0, -1))]);
  checks.push(["isoformat(fraction=1)", esc(iso.slice(0, 20) + fracDigits(millis3, 1) + "Z")]);
  checks.push(["isoformat(fraction=2)", esc(iso.slice(0, 20) + fracDigits(millis3, 2) + "Z")]);
  checks.push(["isoformat(fraction=6)", esc(iso.slice(0, 20) + fracDigits(millis3, 6) + "Z")]);
  checks.push(["isoformat(fraction=9)", esc(iso.slice(0, 20) + fracDigits(millis3, 9) + "Z")]);

  out.push(`test "ecma ${idx}" {`);
  for (const [call, expected] of checks) {
    out.push(`  assert_eq(${ctor(c)}.${call}, "${expected}")`);
  }
  out.push("}");
  out.push("");
  idx++;
}

process.stdout.write(out.join("\n") + "\n");
