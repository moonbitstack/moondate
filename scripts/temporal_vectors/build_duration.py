"""Turn the reference's answers about lengths into a MoonBit table.

`duration_cases.mjs` asks the pinned reference implementation a list of questions
about a length and writes down what it said; this decides which of those answers
this library can be asked for and writes the rest as a test.

    python scripts/temporal_vectors/build_duration.py --cases duration.json \\
        --out src/period_vectors_test.mbt

Every third question is kept, which is a sample rather than the whole list: the
reference answers thousands of combinations and the point of the table is to say
what the shapes of the answers are, not to enumerate every arithmetic coincidence.
The sample is taken by position, so the same corpus gives the same table.
"""

import argparse
import json
import sys

UNITS = ["years", "months", "weeks", "days", "hours", "minutes", "seconds",
         "milliseconds", "microseconds", "nanoseconds"]
ROUNDING = ["ceil", "floor", "expand", "trunc", "halfCeil", "halfFloor",
            "halfExpand", "halfTrunc", "halfEven"]


def fields_of(entry):
    return (entry["years"], entry["months"], entry["weeks"], entry["days"],
            entry["hours"], entry["minutes"], entry["seconds"],
            entry["milliseconds"] * 10**6 + entry["microseconds"] * 10**3
            + entry["nanoseconds"])


def lit(value):
    if isinstance(value, tuple):
        return "(" + ", ".join(lit(item) for item in value) + ")"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        if -(2**31) <= value < 2**31:
            return str(value)
        return str(value) + "L"
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise ValueError(value)




def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    data = json.load(open(args.cases, encoding="utf-8"))
    rounds, totals, compares, parses = [], [], [], []

    for index, entry in enumerate(data["rounds"]):
        if index % 3:
            continue
        if not entry["ok"]:
            # A rounding the reference refuses is a question with no answer, and
            # this library refuses on its own terms; only answers are tabled.
            continue
        want = fields_of(entry["fields"])
        rounds.append([
            lit(fields_of(entry["length"])),
            lit(UNITS.index(entry["unit"])),
            lit(ROUNDING.index(entry["mode"])),
            lit(entry["start"]),
            lit(want),
        ])

    for entry in data["totals"]:
        if not entry["ok"]:
            continue
        totals.append([
            lit(fields_of(entry["length"])),
            lit(UNITS.index(entry["unit"])),
            lit(entry["start"]),
            lit(float(round(entry["value"], 9))),
        ])

    for entry in data["compares"]:
        if not entry["ok"]:
            continue
        compares.append([
            lit(fields_of(entry["left"])),
            lit(fields_of(entry["right"])),
            lit(entry["start"]),
            lit(entry["value"]),
        ])

    for entry in data["parses"]:
        if not entry["ok"]:
            continue
        parses.append([lit(entry["text"]), lit(fields_of(entry["fields"]))])

    def table(name, members, rows, chunk=200):
        out = ["///|\nstruct %s {\n" % name]
        names = []
        for member in members.split(";"):
            out.append("  %s\n" % member.strip())
            names.append(member.split(":")[0].strip())
        out.append("}\n\n")
        pieces = [rows[i:i + chunk] for i in range(0, len(rows), chunk)]
        for number, piece in enumerate(pieces, start=1):
            out.append("///|\nfn %s_part_%d(out : Array[%s]) -> Unit {\n" % (name.lower(), number, name))
            for item in piece:
                pairs = ", ".join("%s: %s" % (name, value)
                                  for name, value in zip(names, item))
                out.append("  out.push({ %s })\n" % pairs)
            out.append("}\n\n")
        out.append("///|\nfn %s_all() -> Array[%s] {\n  let out : Array[%s] = []\n" % (name.lower(), name, name))
        for number in range(1, len(pieces) + 1):
            out.append("  %s_part_%d(out)\n" % (name.lower(), number))
        out.append("  out\n}\n\n")
        return "".join(out)

    head = """// Generated by scripts/temporal_vectors/build_duration.py from the answers of
// temporal-polyfill, DON'T EDIT IT. Run the scripts in scripts/temporal_vectors/
// to make it again.
//
// %d roundings, %d totals, %d comparisons and %d texts, each one a question the
// reference implementation was asked and answered.

""" % (len(rounds), len(totals), len(compares), len(parses))

    body = ""
    body += table("RoundCase",
                  "length : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64); "
                  "unit : Int32; mode : Int32; start : String; "
                  "want : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64)",
                  rounds, 120)
    body += table("TotalCase",
                  "length : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64); "
                  "unit : Int32; start : String; want : Double",
                  totals, 150)
    body += table("CompareCase",
                  "left : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64); "
                  "right : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64); "
                  "start : String; want : Int32",
                  compares, 150)
    body += table("ParseCase", "text : String; want : (Int64, Int64, Int64, Int64, Int64, Int64, Int64, Int64)",
                  parses, 100)

    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(head + body)
    print("rows: %d rounds, %d totals, %d compares, %d parses"
          % (len(rounds), len(totals), len(compares), len(parses)))


if __name__ == "__main__":
    main()
