"""Turn the cases collected from test262 into a MoonBit test.

The collector (collect.mjs) writes what the corpus asserts; this decides which of
those assertions this library answers, writes them down as data, and says what it
left out and why. Nothing is invented here: every line of the table comes from
`--cases`, and a case is either transcribed or listed under a reason.

    python scripts/temporal_vectors/build.py --cases temporal.json \\
        --out src/temporal_vectors_wbtest.mbt

Run `collect.mjs` first; its header says which commit of test262 it read.
"""

import json
import re
import sys
from typing import Optional

HEADER = """// Generated by scripts/temporal_vectors/build.py from test262 at {pin},
// DON'T EDIT IT. Run the scripts in scripts/temporal_vectors/ to make it again.
//
// {transcribed} of the {total} cases test262 states about reading a zoned date
// and time are answered here: {valued} readings, {zoned} time zone names, and
// {refused} refusals. The other {excluded} need something this package does not
// have, and the reasons are counted in the script's report.
"""


def split_brackets(text: str):
    """The text before the first `[`, and the annotations in order."""
    first = text.find("[")
    if first < 0:
        return text, []
    return text[:first], re.findall(r"\[([^\]]*)\]", text)


def fixed_zone(annotation: str) -> Optional[int]:
    """The offset in seconds a `[+01:00]` names, or None when it names a place."""
    if annotation == "UTC":
        return 0
    found = re.fullmatch(r"([+-])(\d{2}):(\d{2})(?::(\d{2}))?", annotation)
    if not found:
        return None
    total = int(found.group(2)) * 3600 + int(found.group(3)) * 60
    if found.group(4):
        total += int(found.group(4))
    return -total if found.group(1) == "-" else total


def reason_to_skip(case: dict):
    """Why this library cannot answer a case, or None when it can.

    A refusal is the easier half: test262 says the text must throw, so a parser
    that throws is right, whatever the reason. Only the three ways this parser is
    more permissive than Temporal can spoil that, and they are listed first.
    """
    text = case["input"]
    body, annotations = split_brackets(text)
    refused = "thrown" in case

    if refused:
        # `parse` is not `ZonedDateTime.from`: a text with no zone is a plain
        # moment or an instant here, and both are answers.
        if not annotations:
            return "a text that names no zone, which this parser reads"
        # The parser keeps the nanoseconds it can hold and drops the rest.
        found = re.search(r"T\d{2}:\d{2}(?::\d{2})?\.(\d+)", body)
        if found and len(found.group(1)) > 9:
            return "a fraction longer than nine digits, which is truncated here"
        # A leap second is read as the minute it opens.
        if re.search(r"T\d{2}:\d{2}:60", body):
            return "a leap second, read here as the next minute"
        # The minus sign of the world outside ASCII, which this parser does not
        # recognise as a sign at all.
        if "\u2212" in text:
            return "a minus sign that is not the ASCII one"
        # An offset with seconds is read as far as its minutes and the rest is
        # dropped, where Temporal refuses the text.
        if re.search(r"T[^[]*[+-]\d{2}:\d{2}:\d{2}", body):
            return "an offset with seconds"
        if annotations and re.search(r"[+-]\d{2}:\d{2}:\d{2}", annotations[0]):
            return "an offset with seconds"
        # The two ends of Temporal's range: this library's years go further, so
        # it reads a date the corpus says is out of bounds.
        year = re.match(r"([+-]?\d{4,6})-", body)
        if year:
            value = int(year.group(1))
            if value <= -271821 or value >= 275760:
                return "a year outside Temporal's range"
        # An offset beside a zone that disagrees with it is refused by Temporal
        # and accepted here, because accepting it means resolving the zone.
        if annotations and fixed_zone(annotations[0]) is not None and "T" in body:
            found = re.search(r"(Z|[+-][0-9:.,]*)$", body.split("T", 1)[1])
            if found and found.group(1) != "Z":
                written = offset_seconds(found.group(1))
                if written is not None and written != fixed_zone(annotations[0]):
                    return "a text offset that disagrees with its zone"
        return None

    # Temporal reads annotations that are not part of this library's grammar.
    if any("=" in note for note in annotations):
        return "calendar or key-value annotation"
    if any(note.startswith("!") for note in annotations):
        return "critical annotation"
    if len(annotations) > 1:
        return "more than one annotation"

    # A zone named by a place rather than by an offset needs the database, and
    # the root package carries none: that is what tzdata is for.
    if annotations and fixed_zone(annotations[0]) is None:
        return "a zone that needs the database"

    # The offset written beside a zone can disagree with it, and Temporal refuses
    # the pair by default. Deciding that means resolving the zone.
    if annotations and "T" in body:
        found = re.search(r"(Z|[+-][0-9:.,]*)$", body.split("T", 1)[1])
        # `Z` is an exact time rather than a wall clock, so it is not compared
        # with the zone: `1970-01-01T00:00Z[+01:00]` is the epoch read at +01:00.
        if found and found.group(1) != "Z":
            written = offset_seconds(found.group(1))
            if written is not None and written != fixed_zone(annotations[0]):
                return "a text offset that disagrees with its zone"

    # A clock written without colons is the basic form, which also explains why
    # no minutes are found below.
    if "T" in body and re.match(r"\d{6}", body.split("T", 1)[1]):
        return "the basic (no-colon) form"

    # The offset, in each of the shapes ISO 8601 allows and RFC 3339 does not.
    if "T" in body:
        found = re.search(r"(Z|[+-][0-9:.,]*)$", body.split("T", 1)[1])
        if found:
            written = found.group(1)
            if re.fullmatch(r"[+-]\d{4}[.,]\d+", written) or re.fullmatch(
                r"[+-]\d{6}[.,]\d+", written
            ):
                return "the basic (no-colon) form"
            if re.fullmatch(r"[+-]\d{4}", written) or re.fullmatch(
                r"[+-]\d{6}", written
            ):
                return "the basic (no-colon) form"
            if re.fullmatch(r"[+-]\d{2}", written):
                return "an offset with no minutes"
            if re.fullmatch(r"[+-]\d{2}:\d{2}:\d{2}([.,]\d+)?", written):
                return "an offset with seconds"

    # ISO 8601's basic format for the date and the clock.
    if re.match(r"\d{8}", body) or re.match(r"[+-]\d{6}\d{4}", body):
        return "the basic (no-colon) form"
    if not re.match(r"[+-]?\d{4,6}-\d{2}-\d{2}", body):
        return "a date this parser does not read"

    if re.search(r"T[^+-]*,\d", body):
        return "a comma before the fraction"

    # A leap second is read as the minute it opens, which keeps the instant and
    # moves the fields; Temporal keeps the fields and clamps to the second before.
    if re.search(r"T\d{2}:\d{2}:60", body):
        return "a leap second, read here as the next minute"

    if "T" in body:
        clock = body.split("T", 1)[1]
        if re.search(r"[+-]", clock):
            clock = re.split(r"[+-]", clock, maxsplit=1)[0]
        if not re.match(r"\d{2}:\d{2}", clock):
            return "a time with no minutes"
    return None


def offset_seconds(text: str) -> Optional[int]:
    if text == "Z":
        return 0
    found = re.fullmatch(r"([+-])(\d{2})(?::(\d{2}))?(?::(\d{2}))?", text)
    if not found:
        return None
    total = int(found.group(2)) * 3600 + int(found.group(3) or 0) * 60
    total += int(found.group(4) or 0)
    return -total if found.group(1) == "-" else total


def quote(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out + '"'


def split_ns(nanoseconds: str):
    """An instant in nanoseconds as floor seconds and the nanoseconds after."""
    total = int(nanoseconds)
    seconds = total // 1_000_000_000
    nano = total - seconds * 1_000_000_000
    return seconds, nano


# `moon fmt` leaves a row alone up to this width and breaks it after it, so the
# generator writes the same shape and the file does not change under the
# formatter. A transcription that fmt rewrote would make `--check` useless.
ROW_WIDTH = 81


def row(content: str):
    single = "  (" + content + "),"
    if len(single) <= ROW_WIDTH:
        return [single]
    return ["  (", "    " + content + ",", "  ),"]


def render(pin: str, cases, skipped, counts) -> str:
    out = [
        HEADER.format(
            pin=pin,
            total=counts["total"],
            transcribed=counts["transcribed"],
            valued=counts["valued"],
            zoned=counts["zoned"],
            refused=counts["refused"],
            excluded=counts["excluded"],
        )
    ]
    out.append("///|")
    out.append("/// `(text, seconds since 1970, nanoseconds, the zone it names)`.")
    out.append("let readings : Array[(String, Int64, Int64, String)] = [")
    for case in cases:
        if case.get("epochNanoseconds") is None:
            continue
        seconds, nano = split_ns(case["epochNanoseconds"])
        out.extend(
            row(
                "{}, {}L, {}L, {}".format(
                    quote(case["input"]),
                    seconds,
                    nano,
                    quote(case["timeZoneId"] or ""),
                )
            )
        )
    out.append("]")
    out.append("")
    out.append("///|")
    out.append("/// `(text, the name it must be filed under)`.")
    out.append("let names : Array[(String, String)] = [")
    for case in cases:
        if case.get("epochNanoseconds") is not None or "thrown" in case:
            continue
        out.extend(
            row("{}, {}".format(quote(case["input"]), quote(case["timeZoneId"] or "")))
        )
    out.append("]")
    out.append("")
    out.append("///|")
    out.append('/// The texts test262 says must be refused, with the error it names.')
    out.append("let refusals : Array[(String, String)] = [")
    for case in cases:
        if "thrown" not in case:
            continue
        out.extend(row("{}, {}".format(quote(case["input"]), quote(case["thrown"]))))
    out.append("]")
    out.append("")
    return "\n".join(out)


def main() -> None:
    cases_path = None
    out_path = None
    report_path = None
    argv = sys.argv[1:]
    for i in range(0, len(argv), 2):
        if argv[i] == "--cases":
            cases_path = argv[i + 1]
        elif argv[i] == "--out":
            out_path = argv[i + 1]
        elif argv[i] == "--report":
            report_path = argv[i + 1]
    if not cases_path or not out_path:
        print("usage: build.py --cases <json> --out <mbt> [--report <path>]")
        raise SystemExit(2)

    with open(cases_path, encoding="utf-8") as handle:
        collected = json.load(handle)

    merged = {}
    for case in collected["corpus"]:
        text = case["input"]
        known = merged.setdefault(
            text, {"input": text, "epochNanoseconds": None, "timeZoneId": "", "thrown": None}
        )
        if "thrown" in case:
            if known["thrown"] not in (None, case["thrown"]):
                raise SystemExit("two verdicts for " + text)
            known["thrown"] = case["thrown"]
            continue
        if known["thrown"] is not None:
            raise SystemExit("both a verdict and a value for " + text)
        if case.get("epochNanoseconds"):
            if known["epochNanoseconds"] not in (None, case["epochNanoseconds"]):
                raise SystemExit("two instants for " + text)
            known["epochNanoseconds"] = case["epochNanoseconds"]
        if case.get("timeZoneId"):
            if known["timeZoneId"] not in ("", case["timeZoneId"]):
                raise SystemExit("two zones for " + text)
            known["timeZoneId"] = case["timeZoneId"]
    corpus = []
    for known in merged.values():
        if known["thrown"] is not None:
            corpus.append({"input": known["input"], "thrown": known["thrown"]})
        else:
            corpus.append(
                {
                    "input": known["input"],
                    "epochNanoseconds": known["epochNanoseconds"],
                    "timeZoneId": known["timeZoneId"],
                }
            )

    kept = []
    skipped = {}
    for case in corpus:
        reason = reason_to_skip(case)
        if reason is None:
            kept.append(case)
        else:
            skipped.setdefault(reason, []).append(case)

    counts = {
        "total": len(corpus),
        "transcribed": len(kept),
        "valued": sum(1 for c in kept if c.get("epochNanoseconds") is not None),
        "zoned": sum(
            1 for c in kept if c.get("epochNanoseconds") is None and "thrown" not in c
        ),
        "refused": sum(1 for c in kept if "thrown" in c),
        "excluded": len(corpus) - len(kept),
    }

    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(collected.get("pin", "unknown"), kept, skipped, counts))

    lines = [
        "test262 at {}".format(collected.get("pin", "unknown")),
        "{} files, {} cases".format(collected.get("files"), len(corpus)),
        "transcribed {}: {} readings, {} names, {} refusals".format(
            counts["transcribed"],
            counts["valued"],
            counts["zoned"],
            counts["refused"],
        ),
        "excluded {}".format(counts["excluded"]),
    ]
    for reason, items in sorted(skipped.items(), key=lambda kv: -len(kv[1])):
        lines.append("  {:3d}  {}".format(len(items), reason))
    text = "\n".join(lines) + "\n"
    print(text, end="")
    if report_path:
        with open(report_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)


if __name__ == "__main__":
    main()
