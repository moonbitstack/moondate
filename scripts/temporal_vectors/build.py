"""Turn the cases collected from test262 into a MoonBit test.

The collector (collect.mjs) writes what the corpus asserts; this decides which of
those assertions this library answers, writes them down as data, and says what it
left out and why. Nothing is invented here: every line of the table comes from
`--cases`, and a case is either transcribed or listed under a reason.

    python scripts/temporal_vectors/build.py --cases temporal.json \\
        --out src/temporal_vectors_wbtest.mbt

The cases arrive from more than one suite — a zoned date and time, a plain date,
an instant — and each is its own file, so `--cases` takes them comma separated.

Run `collect.mjs` first; its header says which commit of test262 it read.
"""

import json
import re
import sys
from typing import Optional

HEADER = """// Generated by scripts/temporal_vectors/build.py from test262 at {pin},
// DON'T EDIT IT. Run the scripts in scripts/temporal_vectors/ to make it again.
//
// {transcribed} of the {total} cases test262 states about reading a text into a
// date, an instant or a zoned date and time are answered here; the other
// {excluded} need something this package does not have, and the reasons are
// counted in the script's report.
//
// {zoned} are about a zoned reading, {dated} about a plain date, {instant} about
// an instant, and {partial} about one property of a reading rather than all of
// it. {refused} of the {transcribed} are refusals.
"""

KIND_ZONED = "ZonedDateTime"
KIND_DATE = "PlainDate"
KIND_INSTANT = "Instant"

# The properties a reading has, in the names test262 writes them. A test may state
# one of them and leave the rest alone.
PARTIAL_NAMES = (
    "year",
    "month",
    "day",
    "hour",
    "minute",
    "second",
    "millisecond",
    "microsecond",
    "nanosecond",
)


# ---- reading the text ------------------------------------------------------


def split_brackets(text: str):
    """The text before the first `[`, and the annotations in order."""
    first = text.find("[")
    if first < 0:
        return text, []
    return text[:first], re.findall(r"\[([^\]]*)\]", text)


def fixed_zone(annotation: str) -> Optional[int]:
    """The offset in seconds a `[+01:00]` names, or None when it names a place."""
    if annotation.startswith("!"):
        # `[!UTC]` marks a zone the reader has to understand; the `!` is not its
        # name, and the zone is still UTC.
        annotation = annotation[1:]
    if annotation == "UTC":
        return 0
    found = re.fullmatch(r"([+-])(\d{2}):(\d{2})(?::(\d{2}))?", annotation)
    if not found:
        return None
    total = int(found.group(2)) * 3600 + int(found.group(3)) * 60
    if found.group(4):
        total += int(found.group(4))
    return -total if found.group(1) == "-" else total


def offset_seconds(text: str) -> Optional[int]:
    if text == "Z":
        return 0
    found = re.fullmatch(r"([+-])(\d{2})(?::(\d{2}))?(?::(\d{2}))?", text)
    if not found:
        return None
    total = int(found.group(2)) * 3600 + int(found.group(3) or 0) * 60
    total += int(found.group(4) or 0)
    return -total if found.group(1) == "-" else total


def clock_of(body: str) -> str:
    """The clock of a date and time, without the offset beside it."""
    if "T" not in body:
        return ""
    rest = body.split("T", 1)[1]
    return re.split(r"(?:[+-]|Z|z)", rest, maxsplit=1)[0]


def offset_written(body: str):
    """The offset the text ends with, as written, or None when there is none."""
    if "T" not in body:
        return None
    found = re.search(r"(Z|[+-][0-9:.,]*)$", body.split("T", 1)[1])
    return found.group(1) if found else None


def carries_offset(body: str) -> bool:
    """Whether the text ends with an offset the parser can read."""
    return offset_written(body) is not None


def too_precise(body: str) -> bool:
    """A fraction of a second longer than the nine digits a nanosecond takes."""
    found = re.search(r"T\d{2}:?\d{2}(?::?\d{2})?[.,](\d+)", body)
    return bool(found and len(found.group(1)) > 9)


def leap_second(body: str) -> bool:
    return bool(re.search(r"T\d{2}:?\d{2}:?60", body))


def comma_fraction(body: str) -> bool:
    """A comma where the fraction of a second begins, which is ISO 8601's mark."""
    return bool(re.search(r"T[^+-]*,", body))


def sub_second_offset(body: str) -> bool:
    """An offset finer than a second, which a fixed zone here cannot hold."""
    if "T" not in body:
        return False
    found = re.search(r"[+-]\d{2}:\d{2}:\d{2}[.,](\d+)$", body.split("T", 1)[1])
    return bool(found and any(digit != "0" for digit in found.group(1)))


def minus_zero_year(body: str) -> bool:
    """`-000000` is a sign on a year that is nought, which Temporal refuses."""
    return body.startswith("-000000")


def outside_temporal_year(body: str) -> bool:
    year = re.match(r"([+-]?\d{4,6})-", body)
    if not year:
        return False
    value = int(year.group(1))
    return value <= -271821 or value >= 275760


def unsupported_calendar(annotations):
    """A calendar that is not the field set this library has."""
    for note in annotations:
        key, _, value = note.partition("=")
        if key.startswith("!"):
            key = key[1:]
        if key == "u-ca" and value.lower() not in ("iso8601", "gregory"):
            return "a calendar this library does not have"
    return None


# ---- deciding what to do with a case ---------------------------------------


def case_place(case: dict, name: str):
    """Mark a case whose zone is a place, so it lands in the database's table."""
    case["place"] = name


def reason_to_skip(case: dict):
    """Why this library cannot answer a case, or None when it can."""
    text = case["input"]
    body, annotations = split_brackets(text)
    refused = "thrown" in case
    kind = case.get("kind", KIND_ZONED)
    if kind == KIND_DATE:
        return skip_date(body, annotations, refused, text, case)
    if kind == KIND_INSTANT:
        return skip_instant(body, annotations, refused, text)
    return skip_zoned(body, annotations, refused, text, case)


def skip_zoned(body, annotations, refused, text, case):
    """A zoned date and time: an instant together with the zone it was read in."""
    if refused:
        # `parse` is not `ZonedDateTime.from`: a text with no zone is a plain
        # moment or an instant here, and both are answers.
        if not annotations:
            return "a text that names no zone, which this parser reads"
        if too_precise(body):
            return "a fraction longer than nine digits, which is truncated here"
        if leap_second(body):
            return "a leap second, read here as the next minute"
        if "\u2212" in text:
            return "a minus sign that is not the ASCII one"
        if minus_zero_year(body):
            return "a year of minus zero, which this parser reads as year nought"
        if outside_temporal_year(body):
            return "a year outside Temporal's range"
        # An offset beside a zone that disagrees with it is refused by Temporal
        # and accepted here, because accepting it means resolving the zone.
        if annotations and fixed_zone(annotations[0]) is not None:
            written = offset_written(body)
            if written is not None and written != "Z":
                value = offset_seconds(written)
                if value is not None and value != fixed_zone(annotations[0]):
                    return "a text offset that disagrees with its zone"
        return None

    # Temporal reads annotations that are not part of this library's grammar.
    trouble = unsupported_calendar(annotations)
    if trouble:
        return trouble

    # A zone named by a place is not the root reader's to answer — it has no
    # database — but `@tzdata.parse` is, so the case goes to that table instead.
    if annotations and fixed_zone(annotations[0]) is None:
        if "=" not in annotations[0]:
            case_place(case, annotations[0].lstrip("!"))
        return None

    # The offset written beside a zone can disagree with it. `Z` is an exact time
    # rather than a wall clock, so it is not compared with the zone:
    # `1970-01-01T00:00Z[+01:00]` is the epoch read at +01:00.
    if annotations:
        written = offset_written(body)
        if written is not None and written != "Z":
            value = offset_seconds(written)
            if value is not None and value != fixed_zone(annotations[0]):
                return "a text offset that disagrees with its zone"

    if comma_fraction(body):
        return "a comma before the fraction"

    # A leap second is read as the minute it opens, which keeps the instant and
    # moves the fields; Temporal keeps the fields and clamps to the second before.
    if leap_second(body):
        return "a leap second, read here as the next minute"

    # A clock may be written with colons or without, but it needs its minutes:
    # `15:23`, `1523` and `152330` are times, `15` alone is not.
    if "T" in body:
        clock = clock_of(body)
        if ":" in clock:
            if not re.match(r"\d{2}:\d{2}", clock):
                return "a time with no minutes"
        else:
            lead = len(re.match(r"\d*", clock).group(0))
            if lead not in (2, 4, 6):
                return "a time with no minutes"
    return None


def reads_what_temporal_refuses(body):
    """Why this parser answers a text the corpus says must throw.

    These three are Temporal's own limits rather than differences in reading: a
    year outside its range, a year written as minus zero, and a fraction of a
    second finer than a nanosecond. This library's years go further, its year
    nought has no sign, and a tenth digit is dropped, so each of the three is a
    text it reads and Temporal does not.
    """
    if outside_temporal_year(body):
        return "a year outside Temporal's range"
    if minus_zero_year(body):
        return "a year of minus zero, which this parser reads as year nought"
    if too_precise(body):
        return "a fraction longer than nine digits, which is truncated here"
    return None


def skip_date(body, annotations, refused, text, case):
    """A plain date: the day the text names, with the rest of it ignored."""
    # A date has to be there: a bare clock is a clock to this parser and nothing
    # at all to `PlainDate`. Six or eight digits alone are read as a clock here.
    # The question is the same on both sides of a refusal, and this parser answers
    # it by reading, so a refusal is not answerable either.
    if re.match(r"\d{2}:", body) or re.match(r"T", body):
        return "a text with no date, which this parser reads as a clock"
    if re.match(r"\d{6,8}$", body):
        return "a text with no date, which this parser reads as a clock"
    if refused:
        # Nothing below applies: those checks describe a text `PlainDate` reads and
        # this does not, and a refusal only needs a parser that refuses. What is
        # left is the other direction — the texts this parser reads and the corpus
        # refuses. `PlainDate` will not take a `Z` beside a time at all, because
        # that is a zoned text and a date is not; this parser reads the day of it.
        if "T" in body and offset_written(body) == "Z":
            return "a `Z` beside a time, which PlainDate refuses"
        return reads_what_temporal_refuses(body)
    trouble = unsupported_calendar(annotations)
    if trouble:
        return trouble
    # The day is what is wanted here, so a zone beside it is decoration; a place
    # is still the database's to resolve.
    if annotations and fixed_zone(annotations[0]) is None:
        if "=" not in annotations[0]:
            case_place(case, annotations[0].lstrip("!"))
        return None
    # A test that states one field rather than a whole reading is answered by the
    # field it names, which `partial_of` sorts out; the day itself is not needed.
    if partial_of(case) is not None:
        return None
    # The day rolls into the next one on this clock; Temporal keeps the day and
    # clamps the second.
    if comma_fraction(body):
        return "a comma before the fraction"
    if leap_second(body):
        return "a leap second, read here as the next minute"
    return None


def partial_of(case):
    """The fields a case states, when it states less than a whole date."""
    fields = case.get("fields")
    if fields is None:
        return None
    if all(name in fields for name in ("year", "month", "day")):
        return None
    return fields


def skip_instant(body, annotations, refused, text):
    """An instant: an exact time, which means the text must carry an offset."""
    # A place beside an exact time is decoration; an offset beside it is not.
    if not carries_offset(body):
        return "a text with no offset, which this parser reads as a plain moment"
    if refused:
        # As in `skip_date`: a refusal needs a parser that refuses, and this one
        # refuses an instant only for the reasons the checks below describe.
        return reads_what_temporal_refuses(body)
    trouble = unsupported_calendar(annotations)
    if trouble:
        return trouble
    if "\u2212" in text:
        return "a minus sign that is not the ASCII one"
    if comma_fraction(body):
        return "a comma before the fraction"
    if sub_second_offset(body):
        return "an offset with a fraction of a second, which this parser refuses"
    if too_precise(body):
        return "a fraction longer than nine digits, which is truncated here"
    if minus_zero_year(body):
        return "a year of minus zero, which this parser reads as year nought"
    if leap_second(body):
        return "a leap second, read here as the next minute"
    if outside_temporal_year(body):
        return "a year outside Temporal's range"
    return None


# ---- writing it down -------------------------------------------------------


def quote(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out + '"'


def split_ns(nanoseconds: str):
    """An instant in nanoseconds as floor seconds and the nanoseconds after."""
    total = int(nanoseconds)
    seconds = total // 1_000_000_000
    nano = total - seconds * 1_000_000_000
    return seconds, nano


def row(items):
    """One tuple, on one line.

    The line is not wrapped here: `moon fmt` does that, with a rule about where a
    break reads best that is not a column count, and `run.py` formats the file
    after writing it. Guessing at the rule here would only mean two layouts to
    keep in step.
    """
    return ["  (" + ", ".join(items) + "),"]


def render(pin: str, cases, counts) -> str:
    zoned = [c for c in cases if c.get("kind", KIND_ZONED) == KIND_ZONED]
    dates = [c for c in cases if c.get("kind") == KIND_DATE]
    instants = [c for c in cases if c.get("kind") == KIND_INSTANT]
    # A case that states one field of a reading states something about the text,
    # so it is answered by comparing that field and leaving the rest unasked.
    partial = [c for c in cases if partial_of(c) is not None]
    out = [HEADER.format(pin=pin, **counts)]

    def table(name: str, shape: str, rows):
        # `moon fmt` writes an empty table on one line, so the generator does too.
        if not rows:
            out.append("///|")
            out.append("/// One line per case, in the shape the replay reads.")
            out.append("let {} : Array[{}] = []".format(name, shape))
            out.append("")
            return
        out.append("///|")
        out.append("/// One line per case, in the shape the replay reads.")
        out.append("let {} : Array[{}] = [".format(name, shape))
        for entry in rows:
            out.extend(entry)
        out.append("]")
        out.append("")

    table(
        "readings",
        "(String, Int64, Int64, String)",
        [
            row([
                quote(c["input"]),
                "{}L".format(split_ns(c["epochNanoseconds"])[0]),
                "{}L".format(split_ns(c["epochNanoseconds"])[1]),
                quote(c["timeZoneId"] or ""),
            ])
            for c in zoned
            if c.get("epochNanoseconds") is not None
        ],
    )
    table(
        "names",
        "(String, String)",
        [
            row([quote(c["input"]), quote(c["timeZoneId"] or "")])
            for c in zoned
            if c.get("epochNanoseconds") is None
            and "thrown" not in c
            and partial_of(c) is None
        ],
    )
    table(
        "partial_readings",
        "(String, String, Int32)",
        [
            row([quote(c["input"]), quote(name), str(int(value))])
            for c in partial
            if "thrown" not in c
            for name, value in sorted(c["fields"].items())
            if name in PARTIAL_NAMES
        ],
    )
    table(
        "dates",
        "(String, Int32, Int32, Int32)",
        [
            row([
                quote(c["input"]),
                str(int(c["fields"]["year"])),
                str(int(c["fields"]["month"])),
                str(int(c["fields"]["day"])),
            ])
            for c in dates
            if "thrown" not in c and partial_of(c) is None
        ],
    )
    table(
        "instants",
        "(String, Int64, Int64)",
        [
            row([
                quote(c["input"]),
                "{}L".format(split_ns(c["epochNanoseconds"])[0]),
                "{}L".format(split_ns(c["epochNanoseconds"])[1]),
            ])
            for c in instants
            if c.get("epochNanoseconds") is not None
        ],
    )
    for name, rows in (
        ("refusals", [c for c in zoned if "thrown" in c]),
        ("date_refusals", [c for c in dates if "thrown" in c]),
        ("instant_refusals", [c for c in instants if "thrown" in c]),
    ):
        table(
            name,
            "(String, String)",
            [row([quote(c["input"]), quote(c["thrown"])]) for c in rows],
        )
    return "\n".join(out)


PLACE_HEADER = """// Generated by scripts/temporal_vectors/build.py from test262 at {pin},
// DON'T EDIT IT. Run the scripts in scripts/temporal_vectors/ to make it again.
//
// {total} cases whose text names a zone by a place rather than by an offset —
// {valued} readings and {refused} refusals. These are the ones the root package
// cannot answer, because a place needs the database; @tzdata.parse is what does.
"""


def render_places(pin: str, cases, counts) -> str:
    out = [PLACE_HEADER.format(pin=pin, **counts)]
    valued = [c for c in cases if "thrown" not in c and c.get("epochNanoseconds")]
    dated = [c for c in cases if "thrown" not in c and c.get("fields")]
    refused = [c for c in cases if "thrown" in c]

    def table(name: str, shape: str, rows):
        if not rows:
            out.append("///|")
            out.append("/// One line per case, in the shape the replay reads.")
            out.append("let {} : Array[{}] = []".format(name, shape))
            out.append("")
            return
        out.append("///|")
        out.append("/// One line per case, in the shape the replay reads.")
        out.append("let {} : Array[{}] = [".format(name, shape))
        for entry in rows:
            out.extend(entry)
        out.append("]")
        out.append("")

    table(
        "places",
        "(String, Int64, Int64, String)",
        [
            row([
                quote(c["input"]),
                "{}L".format(split_ns(c["epochNanoseconds"])[0]),
                "{}L".format(split_ns(c["epochNanoseconds"])[1]),
                quote(c["timeZoneId"] or ""),
            ])
            for c in valued
        ],
    )
    table(
        "place_dates",
        "(String, Int32, Int32, Int32)",
        [
            row([
                quote(c["input"]),
                str(int(c["fields"]["year"])),
                str(int(c["fields"]["month"])),
                str(int(c["fields"]["day"])),
            ])
            for c in dated
            if all(k in c["fields"] for k in ("year", "month", "day"))
        ],
    )
    table(
        "place_refusals",
        "(String, String)",
        [row([quote(c["input"]), quote(c["thrown"])]) for c in refused],
    )
    return "\n".join(out)


def merge_fields(known, more, text):
    """The fields of one text, as every file that states one of them states it.

    Two tests may read different properties of the same reading — one the year,
    another the month — and both are true of it, so the fields are gathered rather
    than chosen between. A disagreement is a corpus that contradicts itself.
    """
    if known is None:
        return dict(more)
    for name, value in more.items():
        if name in known and known[name] != value:
            raise SystemExit("two " + name + " values for " + text)
        known[name] = value
    return known


def main() -> None:
    cases_path = None
    out_path = None
    places_path = None
    report_path = None
    argv = sys.argv[1:]
    for i in range(0, len(argv), 2):
        if argv[i] == "--cases":
            cases_path = argv[i + 1]
        elif argv[i] == "--out":
            out_path = argv[i + 1]
        elif argv[i] == "--places-out":
            places_path = argv[i + 1]
        elif argv[i] == "--report":
            report_path = argv[i + 1]
    if not cases_path or not out_path:
        print("usage: build.py --cases <json>[,<json>] --out <mbt> [--report <path>]")
        raise SystemExit(2)

    corpus = []
    pin = None
    for path in cases_path.split(","):
        with open(path, encoding="utf-8") as handle:
            collected = json.load(handle)
        pin = pin or collected.get("pin", "unknown")
        corpus.extend(collected["corpus"])

    # One case per text and kind: a file may state the same reading twice, and a
    # text means different things to `PlainDate.from` and `ZonedDateTime.from`.
    merged = {}
    for case in corpus:
        kind = case.get("kind", KIND_ZONED)
        key = (kind, case["input"])
        known = merged.setdefault(
            key,
            {
                "input": case["input"],
                "kind": kind,
                "epochNanoseconds": None,
                "timeZoneId": "",
                "fields": None,
                "thrown": None,
            },
        )
        if "thrown" in case:
            if known["thrown"] not in (None, case["thrown"]):
                raise SystemExit("two verdicts for " + case["input"])
            known["thrown"] = case["thrown"]
            continue
        if known["thrown"] is not None:
            raise SystemExit("both a verdict and a value for " + case["input"])
        if case.get("epochNanoseconds"):
            if known["epochNanoseconds"] not in (None, case["epochNanoseconds"]):
                raise SystemExit("two instants for " + case["input"])
            known["epochNanoseconds"] = case["epochNanoseconds"]
        if case.get("timeZoneId"):
            if known["timeZoneId"] not in ("", case["timeZoneId"]):
                raise SystemExit("two zones for " + case["input"])
            known["timeZoneId"] = case["timeZoneId"]
        if case.get("fields"):
            known["fields"] = merge_fields(
                known["fields"], case["fields"], case["input"]
            )

    dressed = []
    for known in merged.values():
        if known["thrown"] is not None:
            dressed.append(
                {"input": known["input"], "kind": known["kind"], "thrown": known["thrown"]}
            )
        elif known["fields"] is not None:
            dressed.append(
                {"input": known["input"], "kind": known["kind"], "fields": known["fields"]}
            )
        else:
            dressed.append(
                {
                    "input": known["input"],
                    "kind": known["kind"],
                    "epochNanoseconds": known["epochNanoseconds"],
                    "timeZoneId": known["timeZoneId"],
                }
            )

    kept = []
    skipped = {}
    for case in dressed:
        reason = reason_to_skip(case)
        if reason is None:
            kept.append(case)
        else:
            skipped.setdefault(reason, []).append(case)

    # A case whose zone is a place belongs to the database, and the file it goes
    # into is the one the package that owns the database compiles.
    places = [c for c in kept if c.get("place")]
    kept = [c for c in kept if not c.get("place")]

    def kept_of(kind):
        return [c for c in kept if c.get("kind", KIND_ZONED) == kind]

    counts = {
        "total": len(dressed),
        "transcribed": len(kept),
        # The four kinds are counted apart so that they add up: a case that
        # states one property is counted there and not among the readings it
        # would otherwise have been one of.
        "zoned": len([c for c in kept_of(KIND_ZONED) if partial_of(c) is None]),
        "dated": len([c for c in kept_of(KIND_DATE) if partial_of(c) is None]),
        "instant": len([c for c in kept_of(KIND_INSTANT) if partial_of(c) is None]),
        "partial": len([c for c in kept if partial_of(c) is not None]),
        "refused": sum(1 for c in kept if "thrown" in c),
        "excluded": len(dressed) - len(kept) - len(places),
    }

    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(pin, kept, counts))

    place_counts = {
        "total": len(places),
        "valued": sum(1 for c in places if "thrown" not in c),
        "refused": sum(1 for c in places if "thrown" in c),
    }
    if places_path:
        with open(places_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render_places(pin, places, place_counts))

    lines = [
        "test262 at {}".format(pin),
        "{} cases: {} zoned, {} dates, {} instants".format(
            len(dressed),
            sum(1 for c in dressed if c.get("kind", KIND_ZONED) == KIND_ZONED),
            sum(1 for c in dressed if c.get("kind") == KIND_DATE),
            sum(1 for c in dressed if c.get("kind") == KIND_INSTANT),
        ),
        "transcribed {} ({} refusals): {} zoned, {} dates, {} instants".format(
            counts["transcribed"],
            counts["refused"],
            counts["zoned"],
            counts["dated"],
            counts["instant"],
        ),
        "{} of those state one field of a reading rather than all of it".format(
            counts["partial"]
        ),
        "and {} whose zone is a place, for @tzdata.parse".format(len(places)),
        "excluded {}".format(counts["excluded"]),
    ]
    for reason, items in sorted(skipped.items(), key=lambda kv: -len(kv[1])):
        lines.append("  {:3d}  {}".format(len(items), reason))
    text = "\n".join(lines) + "\n"
    print(text, end="")
    if report_path:
        with open(report_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)


