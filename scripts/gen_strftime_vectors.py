# Emit a MoonBit test file whose expected strings come from CPython's own
# strftime, the reference implementation for the C/POSIX directives. Run it, then
# commit the generated src/strftime_vectors_test.mbt; CI replays the tests without
# re-running Python.

import datetime
import sys

# Each case is a datetime plus an offset in minutes (None for a naive wall clock,
# which moondate reads as Plain, Day or Clock).
CASES = [
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, u=123456, off=480),
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, u=123456, off=0),
    dict(y=1999, m=1, d=5, H=3, M=4, S=7, u=0, off=0),
    dict(y=2000, m=2, d=29, H=23, M=59, S=59, u=0, off=-330),
    dict(y=2026, m=9, d=22, H=14, M=30, S=5, u=123456, off=None),
    dict(y=1999, m=1, d=5, H=0, M=0, S=0, u=0, off=None),
    dict(y=2000, m=2, d=29, H=23, M=59, S=59, u=0, off=None),
]

FORMATS = [
    "%Y", "%C", "%y", "%G", "%g", "%m", "%B", "%b", "%h", "%d", "%e", "%j",
    "%U", "%W", "%V", "%u", "%w", "%a", "%A", "%H", "%I", "%M", "%S", "%p",
    "%f", "%z", "%Z", "%c", "%x", "%X", "%D", "%R", "%r", "%n", "%t", "%%",
    "%Y-%m-%d %H:%M:%S", "%G-W%V-%u", "%Y-%m-%dT%H:%M:%S%z",
    "%Y-%m-%d %j", "%Y %U %w", "%Y %W %w", "%I:%M:%S %p",
]


def make_dt(c):
    base = datetime.datetime(c["y"], c["m"], c["d"], c["H"], c["M"], c["S"], c["u"])
    if c["off"] is None:
        return base, None
    tz = datetime.timezone(datetime.timedelta(minutes=c["off"]))
    return base.replace(tzinfo=tz), c["off"]


def ctor(c):
    if c["off"] is None:
        return (
            "v_plain(%d, %d, %d, %d, %d, %d, %d)"
            % (c["y"], c["m"], c["d"], c["H"], c["M"], c["S"], c["u"])
        )
    return (
        "v_zoned(%d, %d, %d, %d, %d, %d, %d, %d)"
        % (c["y"], c["m"], c["d"], c["H"], c["M"], c["S"], c["u"], c["off"])
    )


def main():
    out = []
    out.append("// Generated by scripts/gen_strftime_vectors.py from CPython's strftime.")
    out.append("// The expected strings are CPython's own output; do not edit by hand.")
    out.append("")
    out.append(
        "fn v_zoned(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, "
        "sec : Int32, u : Int32, off : Int32) -> @moondate.Moment raise @moondate.Refused {"
    )
    out.append(
        "  @moondate.Moment::Zoned(date=@moondate.Date::new(y, m, d), "
        "time=@moondate.Time::new(hh, mi, second=sec, nano=u * 1000), "
        "zone=@moondate.Offset(off))"
    )
    out.append("}")
    out.append("")
    out.append(
        "fn v_plain(y : Int32, m : Int32, d : Int32, hh : Int32, mi : Int32, "
        "sec : Int32, u : Int32) -> @moondate.Moment raise @moondate.Refused {"
    )
    out.append(
        "  @moondate.Moment::Plain(date=@moondate.Date::new(y, m, d), "
        "time=@moondate.Time::new(hh, mi, second=sec, nano=u * 1000))"
    )
    out.append("}")
    out.append("")

    cases = [make_dt(c) for c in CASES]
    idx = 0
    batch = []
    blocks = []
    for i, (dt, _off) in enumerate(cases):
        c = CASES[i]
        lines = []
        for fmt in FORMATS:
            try:
                expected = dt.strftime(fmt)
            except Exception as e:
                sys.stderr.write("skip %r on %r: %s\n" % (fmt, dt, e))
                continue
            # Newlines and tabs are awkward to assert literally; escape them.
            shown = (
                expected.replace("\\", "\\\\")
                .replace('"', '\\"')
                .replace("\n", "\\n")
                .replace("\t", "\\t")
            )
            lines.append(
                '  assert_eq(%s.strftime("%s"), "%s")'
                % (ctor(c), fmt, shown)
            )
        blk = (
            "test \"python vectors #%d (%s)\" {\n" % (i, ctor(c))
            + "\n".join(lines)
            + "\n}\n"
        )
        blocks.append(blk)
    out.extend(blocks)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
